export const getBusColor = (busName) => {
  switch (busName) {
    case "24":
    case "26-3":
    case "31-1":
    case "39-1":
      return "text-[#FFAA00]";
    case "720-3":
      return "text-[#42C00C]";
    case "102":
    case "1101":
    case "1101N":
    case "8100":
    case "7007-1":
    case "8100(예약)":
      return "text-[#FF2F2F]";
    case "셔틀버스":
      return "text-[#2373FF]";
    default:
      return "text-gray-800";
  }
};

